"""A bounded, canonical wrapper around the frozen arithmetic primitives.

The model adapter supplies a fresh context manager on every call. Its cdf()
method sees only the state built by advance(decoded_scale). No transmitter CDF
or original tokens enter decode_prefix. Integer coding remains the old core.
"""
from __future__ import annotations
from dataclasses import dataclass
import numpy as np
from h64_catalog import SIZES, require

ZERO_EXTENSION_LIMIT = 30
CODEC_PROTOCOL = dict(integer_precision_bits=32, cdf_total=1 << 24,
    alphabet=4096, minimum_frequency=1, cdf_rounding='floor_mass_plus_one',
    cdf_remainder='first_argmax_probability', ordering='raster',
    stream='one_continuous_complete_prefix', termination='legacy_finish_pending_plus_two',
    zero_extension_limit=ZERO_EXTENSION_LIMIT,
    canonical_validation='receiver_reencode_exact_bit_equality_and_exact_30_zero_reads',
    external_padding='never passed to arithmetic decoder', class_condition=1000, cfg=False)


class InvalidCodeStream(ValueError):
    pass


@dataclass(frozen=True)
class ArithmeticPrimitives:
    encoder_type: type
    decoder_type: type
    cdf_function: object
    validate_cdf: object


def reference_primitives(whole_entropy_module, entropy_module):
    """Explicitly inject already source-bound old modules; do not import a model here."""
    require(entropy_module.FULL == 1 << 32 and entropy_module.TOTAL == 1 << 24,
            'Registered arithmetic precision differs')
    return ArithmeticPrimitives(whole_entropy_module.ArithmeticEncoder,
        whole_entropy_module.ArithmeticDecoder, entropy_module.probability_cdf,
        entropy_module.validate_cdf)


def validate_tokens(tokens, scale):
    a = np.asarray(tokens)
    require(a.shape == (SIZES[scale] ** 2,) and np.issubdtype(a.dtype, np.integer)
            and np.all((a >= 0) & (a < 4096)), 'Invalid scale token array')
    return a.astype(np.int64, copy=True)


def get_cdf(provider, primitives):
    # The adapter may expose integer CDF directly or the original log_probs API.
    cdf = provider.cdf() if hasattr(provider, 'cdf') else primitives.cdf_function(provider.log_probs())
    return primitives.validate_cdf(cdf)


def encode_prefixes(scales, provider_factory, primitives, modes=(6, 7, 8, 9)):
    require(tuple(modes) == tuple(sorted(set(modes))) and all(m in (6, 7, 8, 9) for m in modes),
            'H arithmetic modes must be an ordered subset of m6..m9')
    require(len(modes) > 0 and len(scales) >= max(modes), 'Missing source scales')
    encoder = primitives.encoder_type()
    results = {}
    with provider_factory() as provider:
        for i in range(max(modes)):
            values = validate_tokens(scales[i], i)
            cdf = get_cdf(provider, primitives)
            require(cdf.shape[0] == len(values), 'CDF does not match current scale')
            encoder.encode(values, cdf)
            provider.advance(values.copy())
            if i+1 in modes:
                bits = np.asarray(encoder.finish(), dtype=np.uint8).copy()
                results[i+1] = dict(bits=bits, arithmetic_bits=len(bits),
                    raw_bits=12*sum(x*x for x in SIZES[:i+1]),
                    flush_bits=len(bits)-len(encoder.bits), mode=i+1)
    return results


def decode_prefix(bits, m, provider_factory, primitives):
    """Decode actual received bits or raise InvalidCodeStream; never correct using truth."""
    require(type(m) is int and m in (6, 7, 8, 9), 'Invalid arithmetic whole-prefix m')
    a = np.asarray(bits)
    if a.ndim != 1 or not np.isin(a, (0, 1)).all() or len(a) < 2:
        raise InvalidCodeStream('Invalid arithmetic payload bits/length')
    a = a.astype(np.uint8, copy=True)

    class BoundedDecoder(primitives.decoder_type):
        def read_bit(self):
            if self.position >= len(self.bits) + ZERO_EXTENSION_LIMIT:
                raise InvalidCodeStream('Arithmetic zero-extension limit exceeded')
            return super().read_bit()

    decoder = BoundedDecoder(a)
    canonical_encoder = primitives.encoder_type()
    recovered = []
    with provider_factory() as provider:
        for scale in range(m):
            cdf = get_cdf(provider, primitives)
            require(cdf.shape[0] == SIZES[scale]**2, 'Receiver CDF does not match current scale')
            try:
                values = decoder.decode(cdf)
            except ValueError as exc:
                raise InvalidCodeStream(str(exc)) from exc
            values = validate_tokens(values, scale)
            # Canonical validation reuses only CDFs generated by this receiver.
            canonical_encoder.encode(values, cdf)
            recovered.append(values.copy())
            provider.advance(values.copy())
    canonical = np.asarray(canonical_encoder.finish(), dtype=np.uint8)
    if not np.array_equal(canonical, a):
        raise InvalidCodeStream('Noncanonical arithmetic termination/length')
    zero_reads = max(0, decoder.position-len(a))
    if zero_reads != ZERO_EXTENSION_LIMIT:
        raise InvalidCodeStream('Unexpected arithmetic terminal lookahead count')
    return dict(scales=recovered, consumed_bits=decoder.position,
                payload_bits=len(a), zero_extension_reads=zero_reads,
                canonical=True, status='SOURCE_DECODED')


def roundtrip(scales, provider_factory, primitives, modes=(6, 7, 8, 9)):
    encoded = encode_prefixes(scales, provider_factory, primitives, modes)
    receipts = {}
    for m, record in encoded.items():
        decoded = decode_prefix(record['bits'], m, provider_factory, primitives)
        require(all(np.array_equal(scales[i], decoded['scales'][i]) for i in range(m)),
                'Independent arithmetic roundtrip mismatch')
        receipts[m] = dict(raw_bits=record['raw_bits'], arithmetic_bits=record['arithmetic_bits'],
            flush_bits=record['flush_bits'], zero_extension_reads=decoded['zero_extension_reads'],
            canonical=True, independent_receiver_factory=True)
    return encoded, receipts
